export function contextBlock(s: SessionState): string {
  const c = s.cardId ? cardById(s.cardId) : null;

  /** 유저가 실제로 쓴 말 — 디렉터가 인용할 수 있는 유일한 재료 */
  const said = s.messages
    .filter((m) => m.role === "user")
    .slice(-8)
    .map((m, i) => `  ${i + 1}. "${m.text}"${m.feelings?.length ? ` [고른 감정: ${m.feelings.join(", ")}]` : ""}`)
    .join("\n");

  const threads = (s.threads ?? []).filter((t) => !t.pulled);

  const cast = [avatarBlock(s), otherBlock(s)].filter(Boolean).join("\n");

  return `[세션 맥락]
무대에 선 배우: ${s.character.name || "(아직 이름 없음 — 없으면 없는 대로 진행하세요)"}${s.character.profile ? ` / ${s.character.profile}` : ""}
뽑힌 카드(소품): ${c ? `${c.emoji} ${c.name} — ${c.keyword}` : "(아직 안 뽑음)"}

${cast || "[출연 인물] 아직 카드가 없습니다. 유저 말에서 받아 세우세요."}

[유저가 직접 고른 감정 — 이 단어들을 그대로 쓰세요. 다른 말로 번역 금지]
${s.feelings?.length ? `  ${s.feelings.join(" · ")}` : "  (아직 없음 — 감정 이름은 유저가 붙이게 하세요)"}

[유저가 최근에 실제로 쓴 말 — 인용은 여기서만 가져오세요]
${said || "  (아직 없음)"}

[아직 안 펼친 실마리]
${threads.length ? threads.map((t) => `  · "${t.text}"`).join("\n") : "  (없음)"}

[지금까지 잡힌 핵심]
가장 아팠던 자리 / 속마음: ${s.coreFeeling || "(아직 없음)"}
1차 반응(실제로 한 말·행동): ${s.firstResponse || "(아직 없음)"}
리플레이 대사: ${s.replayResponse || "(아직 없음)"}

[진행 좌표]
막: ${s.movement || "casting"} · 이 막에서 ${s.beats ?? 0}번째 주고받는 중
깊이: L${s.depth ?? 1} (이 세션 최고 도달 L${s.depthMax ?? s.depth ?? 1})
주고받은 총 횟수: ${s.messages.filter((m) => m.role === "user").length}`;
}

