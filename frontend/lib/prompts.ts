export function contextBlock(s: SessionState): string {
  const c = s.cardId ? cardById(s.cardId) : null;
  return `[세션 맥락]
가상 캐릭터: ${s.character.name || "(미정)"} / ${s.character.profile || "(미정)"}
뽑힌 카드: ${c ? `${c.emoji} ${c.name} — ${c.keyword}` : "(미정)"}
갈등 상대: ${s.other.name || "(미정)"} / 힘든 말: ${s.other.trigger || "(미정)"}
유저가 고른 감정: ${s.feelings?.length ? s.feelings.join(", ") : "(고르지 않음)"}
1막 상황 서술: ${s.answers[4] || "(없음)"}
심화 답변: ${s.answers[7] || "(없음)"}
1차 반응: ${s.firstResponse || "(없음)"}
속마음: ${s.coreFeeling || "(없음)"}
거울 교정: ${s.answers[15] || "(없음)"}
리플레이 대사: ${s.replayResponse || "(없음)"}
현재 턴: ${s.turn}/20`;
}

