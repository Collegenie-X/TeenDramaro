/**
 * 인물 카드(Persona) — character.ai의 Definition/Example-conversation 기법을 이 무대에 옮긴 것.
 *
 * ── 왜 필요했나 ────────────────────────────────────────
 * 지금까지 디렉터는 매 비트 "받아주는 말 1줄 + 질문 1개"만 냈다. 규칙은 많았지만
 * 무대에 사람이 없었다. 사이코드라마의 엔진은 질문이 아니라 보조자아(auxiliary ego)다 —
 * 상대가 실제로 거기 서서 말을 해야 유저가 "다시 해보는" 경험을 한다.
 * 기존 코드에서 상대는 5막에서 저장된 trigger 한 줄을 재생하는 녹음기였다. 그래서 약했다.
 *
 * ── character.ai에서 가져온 것 ─────────────────────────
 *   1) Definition  — 인물을 매 호출마다 다시 주입한다. 상대는 "악역"이 아니라
 *                    원하는 것·무서운 것·말버릇이 있는 사람이다.
 *   2) Example conversation — 규칙 설명보다 예시 한 쌍이 톤을 훨씬 강하게 고정한다.
 *   3) Action line — 대사 앞의 짧은 지문(*시선을 피한다*). 장면에 몸을 준다.
 *   4) Stay-in-character — 상대는 설명하지 않고, 사과를 서비스하지 않는다.
 *
 * ── 가져오지 않은 것 (여기선 해롭다) ───────────────────
 *   · 끝없이 이어지는 몰입 롤플레이 — 청소년 상담 맥락에서 상대역에 오래 묶이면
 *     재연(reenactment)이 된다. 상대는 1~2턴만 서고, 디렉터가 바로 객석으로 데려온다.
 *   · 지문 남용(*...* 도배), 과장된 감정 묘사, 상대의 서사 지분 늘리기.
 *   · 유저를 "너"로 무대에 세우는 1인칭 몰입 — 제0원칙(3인칭 거리)을 깬다.
 */

import type { PersonaCard, SessionState } from "./types";

const dash = (v?: string) => (v && v.trim() ? v.trim() : "");

/** 카드가 비어 있으면(아직 안 만들어졌으면) null — 블록을 아예 안 넣는다 */
export function personaBlock(title: string, p?: PersonaCard | null): string {
  if (!p || !dash(p.name)) return "";
  const rows = [
    `  이름: ${p.name}`,
    dash(p.one) && `  한 줄: ${p.one}`,
    p.speech?.length && `  말버릇(이 인물의 입에서 나올 문장 질감): ${p.speech.map((x) => `"${x}"`).join(" / ")}`,
    dash(p.wants) && `  겉으로 원하는 것: ${p.wants}`,
    dash(p.fears) && `  속으로 무서운 것: ${p.fears}`,
    dash(p.tells) && `  몸에 나오는 것: ${p.tells}`,
    dash(p.nevers) && `  이 인물이 절대 하지 않는 것: ${p.nevers}`,
  ].filter(Boolean);
  return [`[${title}]`, ...rows].join("\n");
}

/** 아바타 카드는 유저가 캐스팅에서 만든 재료로 대체한다 (별도 생성 호출 없음) */
export function avatarBlock(s: SessionState): string {
  if (!s.character.name && !s.character.profile) return "";
  return [
    "[무대에 선 배우 — 유저가 만든 아바타. 이 인물을 연기하지 말고, 이 인물을 무대에 세워라]",
    `  이름: ${s.character.name || "(아직 없음 — '그 애'로 불러라)"}`,
    s.character.profile ? `  유저가 만든 설정: ${s.character.profile}` : "",
    s.coreFeeling ? `  제일 아팠던 자리: ${s.coreFeeling}` : "",
  ].filter(Boolean).join("\n");
}

/**
 * 상대(보조자아) 카드 블록.
 * 카드가 아직 없으면 유저가 준 최소 재료(이름 + 제일 힘든 한마디)로라도 세운다 —
 * 비어 있는 상대는 "평범한 또래"라는 말밖에 못 하고, 그게 지금까지의 약함이었다.
 */
export function otherBlock(s: SessionState): string {
  const card = personaBlock(
    "마주침 상대 — 보조자아 인물 카드 (연기할 때 이 카드 밖으로 나가지 마라)",
    s.other.persona
  );
  if (card) {
    return [card, s.other.trigger ? `  유저가 제일 힘들다고 한 말: "${s.other.trigger}"` : ""]
      .filter(Boolean)
      .join("\n");
  }
  if (!s.other.name && !s.other.trigger) return "";
  return [
    "[마주침 상대 — 아직 인물 카드가 없다. 유저 말에서 더 받아 세워라]",
    `  이름: ${s.other.name || "(아직 없음)"}`,
    s.other.trigger ? `  제일 힘든 말: "${s.other.trigger}"` : "",
  ].filter(Boolean).join("\n");
}

